-- Apply in Supabase SQL editor before deploying the feature.
create table if not exists public.eclairages (
 id bigint generated by default as identity primary key,
 slug text not null unique,
 titre text not null,
 categorie text not null,
 resume text not null,
 contenu text not null,
 sources jsonb not null default '[]'::jsonb,
 publication_date date not null,
 published boolean not null default false,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 constraint eclairages_sources_array check (jsonb_typeof(sources) = 'array')
);
create index if not exists eclairages_public_idx on public.eclairages (publication_date desc) where published;
alter table public.eclairages enable row level security;
revoke all on public.eclairages from anon, authenticated;
grant select on public.eclairages to anon, authenticated;
drop policy if exists "Public can read published eclairages" on public.eclairages;
create policy "Public can read published eclairages" on public.eclairages for select to anon, authenticated
 using (published = true and publication_date <= (now() at time zone 'Europe/Paris')::date);
