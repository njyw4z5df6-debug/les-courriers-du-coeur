create table if not exists public.plume_reactions (
  id bigint generated by default as identity primary key,
  plume_id bigint not null references public.plumes_du_jour(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(plume_id, user_id)
);
create table if not exists public.plume_commentaires (
  id bigint generated by default as identity primary key,
  plume_id bigint not null references public.plumes_du_jour(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  pseudo text not null,
  message text not null check (char_length(message) between 1 and 2000),
  statut text not null default 'en_attente' check (statut in ('en_attente','valide','refuse')),
  created_at timestamptz not null default now()
);
create index if not exists plume_commentaires_moderation on public.plume_commentaires(statut, created_at);
create index if not exists plume_commentaires_plume on public.plume_commentaires(plume_id, statut);
alter table public.plume_reactions enable row level security;
alter table public.plume_commentaires enable row level security;
